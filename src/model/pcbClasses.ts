/**
 * Object classes (Classes6): AD17's Object Class Explorer works on these. Each class has a kind
 * (net, component, from-to, pad, layer, design channel, differential pair, polygon, structure,
 * xSignal [est: the last three's numbers]) and members by name (M0…Mn). "All …" classes are
 * superclasses (every object of the kind); the component classes AD17 generates (Top Side
 * Components …) have their members worked out, not listed.
 */
import type { Change } from '../core/undo';
import { PropertyBag } from '../formats/altium/props';
import { newUniqueId } from '../formats/altium/board6';
import { readClasses, type PcbClass } from '../formats/altium/rules';
import { layerName, L } from './layers';
import { NO_NET, type PcbDocument } from './pcb';
import { cfbStream } from '../formats/cfb/cfb';
import { splitTextRecords } from '../formats/altium/framing';

export const CLASS_KINDS: { kind: number; group: string; one: string; all: string }[] = [
  { kind: 0, group: 'Net Classes', one: 'Net Class', all: 'All Nets' },
  { kind: 1, group: 'Component Classes', one: 'Component Class', all: 'All Components' },
  { kind: 4, group: 'Layer Classes', one: 'Layer Class', all: 'All Layers' },
  { kind: 3, group: 'Pad Classes', one: 'Pad Class', all: 'All Pads' },
  { kind: 2, group: 'From To Classes', one: 'From To Class', all: 'All From-Tos' },
  { kind: 6, group: 'Differential Pair Classes', one: 'Differential Pair Class', all: 'All Differential Pairs' },
  { kind: 5, group: 'Design Channel Classes', one: 'Design Channel Class', all: 'All Design Channels' },
  { kind: 7, group: 'Polygon Classes', one: 'Polygon Class', all: 'All Polygons' },
  { kind: 8, group: 'Structure Classes', one: 'Structure Class', all: 'All Structures' },
  { kind: 9, group: 'xSignal Classes', one: 'xSignal Class', all: 'All xSignals' },
];

const HEAD: [string, string][] = [['SELECTION', 'FALSE'], ['LAYER', 'MULTILAYER'], ['LOCKED', 'FALSE'], ['POLYGONOUTLINE', 'FALSE'], ['USERROUTED', 'TRUE'], ['KEEPOUT', 'FALSE'], ['UNIONINDEX', '0']];

/** A new class as AD17 writes one. */
export function classBag(name: string, kind: number, members: string[] = []): PropertyBag {
  return PropertyBag.fromEntries([
    ...HEAD, ['NAME', name], ['KIND', String(kind)], ['SUPERCLASS', 'FALSE'], ['SELECTED', 'FALSE'],
    ...members.map((m, i): [string, string] => [`M${i}`, m]), ['UNIQUEID', newUniqueId()],
  ]);
}

/** The bag with these members (M0…Mn), its other keys as they were. */
export function withMembers(bag: PropertyBag, members: string[]): PropertyBag {
  const b = bag.clone();
  for (let i = 0; b.has(`M${i}`); i++) b.delete(`M${i}`);
  // Members go after SELECTED, as AD17 writes them, before UNIQUEID
  const uid = b.get('UNIQUEID');
  if (uid !== undefined) b.delete('UNIQUEID');
  members.forEach((m, i) => b.set(`M${i}`, m));
  if (uid !== undefined) b.set('UNIQUEID', uid);
  return b;
}

export const isGenerated = (c: PcbClass) => c.superClass || c.bag.bool('AUTOGENERATEDCLASS');

/** Every object a class of this kind could hold, by the name its members use. */
export function candidates(doc: PcbDocument, kind: number): string[] {
  const byName = (a: string, b: string) => a.localeCompare(b, undefined, { numeric: true });
  switch (kind) {
    case 0: return doc.nets.map((n) => n.name).sort(byName);
    case 1: return doc.components.map((c) => c.designator).filter(Boolean).sort(byName);
    case 3: {
      const out: string[] = [];
      for (const p of doc.prims) if (p.kind === 'pad') { const c = p.component !== NO_NET ? doc.components[p.component]?.designator : undefined; out.push(c ? `${c}-${p.name}` : `Free-${p.name}`); }
      return [...new Set(out)].sort(byName);
    }
    case 4: return [...doc.board.copperStack, L.TOP_OVERLAY, L.BOTTOM_OVERLAY, L.TOP_PASTE, L.BOTTOM_PASTE, L.TOP_SOLDER, L.BOTTOM_SOLDER, L.KEEPOUT, L.MULTI]
      .map((l) => doc.board.layerNames.get(l) ?? layerName(l));
    case 6: return diffPairNames(doc);
    case 7: return doc.polygons.map((p) => p.name).sort(byName);
    default: return [];
  }
}

/** DifferentialPairs6 names (the pairs a differential pair class can hold). */
export function diffPairNames(doc: PcbDocument): string[] {
  if (doc.diffPairs) return doc.diffPairs.map((b) => b.get('NAME') ?? '').filter(Boolean);
  const data = cfbStream(doc.cfb.root, 'DifferentialPairs6/Data');
  try { return data ? splitTextRecords(data).map((b) => b.get('NAME') ?? '').filter(Boolean) : []; } catch { return []; }
}

/** The members a generated component class has on this board (Top Side, Bottom Side, Inside, Outside Board). */
export function membersOf(doc: PcbDocument, c: PcbClass): string[] {
  if (c.superClass) return candidates(doc, c.kind);
  if (c.kind === 1 && c.bag.bool('AUTOGENERATEDCLASS')) {
    const k = c.bag.int('AUTOGENERATEDCLASSKIND');
    const inside = (x: number, y: number) => pointIn(doc.board.outline, x, y);
    return doc.components.filter((comp) => (k === 0 ? comp.layer === L.TOP : k === 1 ? comp.layer === L.BOTTOM : k === 2 ? inside(comp.at.x, comp.at.y) : !inside(comp.at.x, comp.at.y)))
      .map((comp) => comp.designator).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  }
  return c.members;
}
function pointIn(poly: { x: number; y: number }[], x: number, y: number): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const a = poly[i]!, b = poly[j]!;
    if ((a.y > y) !== (b.y > y) && x < ((b.x - a.x) * (y - a.y)) / (b.y - a.y) + a.x) inside = !inside;
  }
  return inside;
}

/** Replace the board's classes (one undo step). */
export function setClasses(doc: PcbDocument, bags: PropertyBag[]): Change {
  const before = doc.classes;
  const after = readClasses(bags.map((b) => b.clone()));
  const was = doc.dirty.has('Classes6');
  return {
    apply() { doc.classes = after; doc.dirty.add('Classes6'); },
    revert() { doc.classes = before; if (!was) doc.dirty.delete('Classes6'); },
  };
}

/** A name not yet taken in this kind ("NetClass", "NetClass1" …). */
export function freshClassName(doc: { classes: PcbClass[] }, kind: number, base?: string): string {
  const b = base ?? (CLASS_KINDS.find((k) => k.kind === kind)?.one.replace(/ /g, '') ?? 'Class');
  const taken = new Set(doc.classes.filter((c) => c.kind === kind).map((c) => c.name.toLowerCase()));
  if (!taken.has(b.toLowerCase())) return b;
  for (let i = 1; ; i++) if (!taken.has(`${b}${i}`.toLowerCase())) return `${b}${i}`;
}

/** Nets of these objects (the selection's), by name. */
export function netsOfSelection(doc: PcbDocument, nets: Iterable<number>): string[] {
  return [...new Set([...nets].filter((n) => n !== NO_NET).map((n) => doc.nets[n]?.name).filter((x): x is string => !!x))];
}
