export function newBoardRules(): PcbRule[] {
  return RULES.map(([kind, name, scope1, priority, own]) => {
    const id = RULE_KIND_IDS[kind] ?? 2;
    return {
      prefix: new Uint8Array([id & 0xff, id >> 8]),
      bag: PropertyBag.fromEntries([
        ...HEAD, ['RULEKIND', kind], ['NETSCOPE', kind === 'Clearance' ? 'DifferentNets' : 'AnyNet'], ['LAYERKIND', 'SameLayer'],
        ['SCOPE1EXPRESSION', scope1], ['SCOPE2EXPRESSION', 'All'], ['NAME', name], ['ENABLED', 'TRUE'], ['PRIORITY', String(priority)],
        ['COMMENT', kind === 'FanoutControl' ? `${name} (Default Rule)` : ''], ['UNIQUEID', newUniqueId()], ['DEFINEDBYLOGICALDOCUMENT', 'FALSE'], ...own,
      ]),
    };
  });
}

/** AD17's board shape for a new PCB: 6000 × 4000 mil with its lower left corner at (1000, 1000) mil. */
export const NEW_BOARD_OUTLINE = [[1000, 1000], [7000, 1000], [7000, 5000], [1000, 5000]].map(([x, y]) => ({ p: { x: mil(x!), y: mil(y!) } }));

/** A new, empty board document (File › New › PCB): PCB1.PcbDoc … */
export function newPcbDocBytes(fileName: string, date = new Date(), outline: { p: { x: number; y: number } }[] = NEW_BOARD_OUTLINE): Uint8Array {
  const root = newEntry('Root Entry', 'root');
  // FileHeader and FileHeaderSix as AD17 writes them (without them AD17 says "File type not recognised")
  const fh = new BinWriter(32).u32(19);
  for (const ch of 'PCB 5.0 Bi') fh.u8(ch.charCodeAt(0)).u8(0);
  cfbPut(root, 'FileHeader', fh.finish());
  const six = binToBytes('PCB 6.0 Binary File');
  cfbPut(root, 'FileHeaderSix', new BinWriter(32).u32(six.length).u8(six.length).bytes(six).f64(5.01).finish());
  const putText = (s: string, bags: PropertyBag[]) => { cfbPut(root, `${s}/Header`, countHeader(bags.length)); cfbPut(root, `${s}/Data`, joinTextRecords(bags)); };
  const board = newBoardRecord({ fileName, origin: { x: 0, y: 0 }, outline, stack: defaultStack(), date });
  putText('Board6', [board]);
  putText('Classes6', newBoardClasses());
  const rules = newBoardRules();
  cfbPut(root, 'Rules6/Header', countHeader(rules.length));
  cfbPut(root, 'Rules6/Data', joinRuleRecords(rules));
  for (const st of ['Nets6', 'Components6']) putText(st, []);
  for (const st of ['Arcs6', 'Pads6', 'Vias6', 'Tracks6', 'Texts6', 'Fills6', 'Regions6', 'ComponentBodies6', 'ShapeBasedComponentBodies6', 'ShapeBasedRegions6',
    'Polygons6', 'Dimensions6', 'Connections6', 'Coordinates6', 'DifferentialPairs6', 'EmbeddedBoards6', 'EmbeddedFonts6', 'Embeddeds6', 'FromTos6', 'Models',
    'ModelsNoEmbed', 'PadViaLibraryLinks', 'PinPairsSection', 'PrimitiveParameters', 'SmartUnions', 'Textures', 'WaivedViolations', 'WideStrings6',
    'ExtendedPrimitiveInformation', 'UniqueIDPrimitiveInformation']) {
    cfbPut(root, `${st}/Header`, countHeader(0)); cfbPut(root, `${st}/Data`, joinBinaryRecords([]));
  }
  return writeCfb(root);
}
