export function newBoardClasses(): PropertyBag[] {
  return CLASSES.map(([name, kind, sup, auto]) => PropertyBag.fromEntries([
    ...HEAD.map(([k, v]): [string, string] => [k, k === 'LAYER' ? 'MULTILAYER' : v]),
    ['NAME', name], ['KIND', String(kind)], ['SUPERCLASS', sup ? 'TRUE' : 'FALSE'],
    ...(auto !== undefined ? [['AUTOGENERATEDCLASS', 'TRUE']] as KV : []),
    ['SELECTED', 'FALSE'], ['SCHAUTOGENERATEDCLUSTER', 'FALSE'], ['UNIQUEID', newUniqueId()],
    ...(auto !== undefined ? [['AUTOGENERATEDCLASSKIND', String(auto)]] as KV : []),
  ]));
}

